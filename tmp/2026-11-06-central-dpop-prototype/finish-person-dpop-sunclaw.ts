import { spawnSync } from "node:child_process";
import { closeSync, openSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const expectedHead = "09a23bc78a55835704e386f66bd0ef3edcdd8128";
const evidence = resolve("tmp/2026-11-06-central-dpop-prototype/sunclaw-09a23bc78");
const env = {
  ...process.env,
  PATH: `/opt/homebrew/opt/rustup/bin:${process.env.PATH ?? ""}`,
  CARGO_BUILD_JOBS: "4",
};
const actualHead = spawnSync("git", ["rev-parse", "HEAD"], { env, encoding: "utf8" }).stdout.trim();
if (actualHead !== expectedHead) throw new Error(`unexpected source ${actualHead}`);
const steps: { name: string; args: string[]; status: number | null }[] = [];
function run(name: string, args: string[], extraEnv: Record<string, string> = {}): void {
  const log = openSync(resolve(evidence, `${name}.log`), "w");
  const result = spawnSync("cargo", args, {
    env: { ...env, ...extraEnv },
    stdio: ["ignore", log, log],
  });
  closeSync(log);
  steps.push({ name, args, status: result.status });
  writeFileSync(
    resolve(evidence, "completion-steps.json"),
    JSON.stringify({ source_head: actualHead, steps }, null, 2),
  );
  if (result.status !== 0) throw new Error(`${name} failed: ${result.status}`);
}
// The original ratchet reported only a pre-existing shrink. Repository policy
// explicitly requires this bless; its implementation refuses any growth.
run(
  "module-cycle-bless",
  ["nextest", "run", "--locked", "-p", "workspace-architecture-check", "--run-ignored", "only"],
  { ARCHITECTURE_BLESS: "1" },
);
run("native-scope-suite", [
  "nextest",
  "run",
  "--locked",
  "-p",
  "collaboration-central-core",
  "-p",
  "collaboration-central-tokio",
]);
writeFileSync(
  resolve(evidence, "completion-succeeded.json"),
  JSON.stringify({
    source_head: actualHead,
    only_source_change:
      "architecture/module-cycle-baseline.json generated by the non-growing bless",
  }),
);
