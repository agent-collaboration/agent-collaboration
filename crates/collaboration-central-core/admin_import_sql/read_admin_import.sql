SELECT CAST(import_id AS TEXT) AS import_id,
typeof(import_id) AS import_id_class,
CAST(project_id AS TEXT) AS project_id,
typeof(project_id) AS project_id_class,
CAST(digest AS TEXT) AS digest,
typeof(digest) AS digest_class,
CAST(provenance_installation AS TEXT) AS provenance_installation,
typeof(provenance_installation) AS provenance_installation_class,
CAST(provenance_machine AS TEXT) AS provenance_machine,
typeof(provenance_machine) AS provenance_machine_class,
CAST(declared_owner AS TEXT) AS declared_owner,
typeof(declared_owner) AS declared_owner_class,
CAST(manifest_epoch AS TEXT) AS manifest_epoch,
typeof(manifest_epoch) AS manifest_epoch_class,
CAST(manifest_sequence AS TEXT) AS manifest_sequence,
typeof(manifest_sequence) AS manifest_sequence_class,
CAST(schema_version AS TEXT) AS schema_version,
typeof(schema_version) AS schema_version_class,
CAST(schema_fingerprint AS TEXT) AS schema_fingerprint,
typeof(schema_fingerprint) AS schema_fingerprint_class,
CAST(pages AS TEXT) AS pages,
typeof(pages) AS pages_class,
CAST(manifest_table_count AS TEXT) AS manifest_table_count,
typeof(manifest_table_count) AS manifest_table_count_class,
CAST(summary_kind AS TEXT) AS summary_kind,
typeof(summary_kind) AS summary_kind_class,
CAST(summary_time_basis AS TEXT) AS summary_time_basis,
typeof(summary_time_basis) AS summary_time_basis_class,
CAST(summary_record_at AS TEXT) AS summary_record_at,
typeof(summary_record_at) AS summary_record_at_class,
CAST(phase_kind AS TEXT) AS phase_kind,
typeof(phase_kind) AS phase_kind_class,
CAST(published_epoch AS TEXT) AS published_epoch,
typeof(published_epoch) AS published_epoch_class,
CAST(published_sequence AS TEXT) AS published_sequence,
typeof(published_sequence) AS published_sequence_class,
CAST(created_at AS TEXT) AS created_at,
typeof(created_at) AS created_at_class,
CAST(updated_at AS TEXT) AS updated_at,
typeof(updated_at) AS updated_at_class
FROM fleet_admin_imports
WHERE project_id = ? AND digest = ?;
