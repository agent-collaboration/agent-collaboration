    time_basis TEXT NOT NULL,
    origin_installation TEXT NOT NULL,
    origin_machine TEXT NOT NULL,
    import_digest TEXT,
    created_at INTEGER NOT NULL,
    updated_at INTEGER NOT NULL
);
CREATE TABLE fleet_workspace_repository_refs (
