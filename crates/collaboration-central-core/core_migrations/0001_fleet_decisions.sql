CREATE TABLE fleet_request_decisions (
    request_id TEXT NOT NULL PRIMARY KEY,
    canonical_hash TEXT NOT NULL,
    workspace_id TEXT NOT NULL,
    board_id TEXT,
    actor_kind TEXT NOT NULL,
    actor_human_id TEXT,
    actor_service_id TEXT,
    actor_endpoint_id TEXT,
    actor_session_id TEXT,
    actor_router_component TEXT,
    envelope_request_id TEXT,
    fleet_position INTEGER NOT NULL,
    router_time TEXT,
    time_basis TEXT NOT NULL,
    origin_installation TEXT NOT NULL,
    origin_machine TEXT NOT NULL,
    created_at INTEGER NOT NULL,
    updated_at INTEGER NOT NULL,
    decision_kind TEXT NOT NULL,
    change_kind TEXT,
    effects_count TEXT,
    effects_digest TEXT,
    reason_count INTEGER NOT NULL
);
CREATE TABLE fleet_decision_reasons (
    reason_id TEXT NOT NULL PRIMARY KEY,
    request_id TEXT NOT NULL REFERENCES fleet_request_decisions(request_id),
    parent_reason_id TEXT REFERENCES fleet_decision_reasons(reason_id),
    ordinal INTEGER NOT NULL,
    refusal_group TEXT NOT NULL,
    refusal_kind TEXT NOT NULL,
    record_kind TEXT,
    record_id TEXT,
    name TEXT,
    field TEXT,
    current_revision TEXT,
    retry_after_seconds TEXT,
    workstream_id TEXT,
    task_id TEXT,
    thread_id TEXT,
    requirement_kind TEXT,
    requirement_role TEXT,
    role_subject_kind TEXT,
    role_subject_id TEXT,
    authority_role TEXT,
    actor_kind TEXT,
    actor_human_id TEXT,
    actor_service_id TEXT,
    actor_endpoint_id TEXT,
    actor_session_id TEXT,
    holder_kind TEXT,
    holder_human_id TEXT,
    holder_service_id TEXT,
    holder_endpoint_id TEXT,
    holder_session_id TEXT,
    target_kind TEXT,
    target_human_id TEXT,
    target_service_id TEXT,
    target_endpoint_id TEXT,
    target_session_id TEXT,
    named_holder_kind TEXT,
    named_holder_human_id TEXT,
    named_holder_service_id TEXT,
    named_holder_endpoint_id TEXT,
    named_holder_session_id TEXT,
    last_seen_epoch TEXT,
    last_seen_position TEXT,
    evidence_kind TEXT,
    evidence_returned_count INTEGER,
    evidence_total_count TEXT,
    evidence_digest TEXT,
    evidence_abridged INTEGER,
    created_at INTEGER NOT NULL,
    updated_at INTEGER NOT NULL,
    UNIQUE(parent_reason_id,ordinal)
);
CREATE INDEX fleet_reason_request ON fleet_decision_reasons(request_id);
CREATE UNIQUE INDEX fleet_root_reason_ordinal ON fleet_decision_reasons(request_id,ordinal) WHERE parent_reason_id IS NULL;
CREATE TABLE fleet_decision_reason_evidence (
    row_id TEXT NOT NULL PRIMARY KEY,
    reason_id TEXT NOT NULL REFERENCES fleet_decision_reasons(reason_id),
    ordinal INTEGER NOT NULL,
    entry_kind TEXT NOT NULL,
    task_id TEXT,
    assignment_kind TEXT,
    assignment_project_id TEXT,
    assignment_workstream_id TEXT,
    created_at INTEGER NOT NULL,
    updated_at INTEGER NOT NULL,
    UNIQUE(reason_id,ordinal)
);
