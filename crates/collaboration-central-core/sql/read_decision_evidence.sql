SELECT CAST(node.row_id AS TEXT) AS row_id,
typeof(node.row_id) AS row_id_class,
CAST(node.reason_id AS TEXT) AS reason_id,
typeof(node.reason_id) AS reason_id_class,
CAST(node.ordinal AS TEXT) AS ordinal,
typeof(node.ordinal) AS ordinal_class,
CAST(node.entry_kind AS TEXT) AS entry_kind,
typeof(node.entry_kind) AS entry_kind_class,
CAST(node.task_id AS TEXT) AS task_id,
typeof(node.task_id) AS task_id_class,
CAST(node.assignment_kind AS TEXT) AS assignment_kind,
typeof(node.assignment_kind) AS assignment_kind_class,
CAST(node.assignment_project_id AS TEXT) AS assignment_project_id,
typeof(node.assignment_project_id) AS assignment_project_id_class,
CAST(node.assignment_workstream_id AS TEXT) AS assignment_workstream_id,
typeof(node.assignment_workstream_id) AS assignment_workstream_id_class,
CAST(node.created_at AS TEXT) AS created_at,
typeof(node.created_at) AS created_at_class,
CAST(node.updated_at AS TEXT) AS updated_at,
typeof(node.updated_at) AS updated_at_class
FROM fleet_decision_reason_evidence AS node JOIN fleet_decision_reasons AS parent ON parent.reason_id=node.reason_id WHERE parent.request_id IN (SELECT CAST(value AS TEXT) FROM json_each(?)) ORDER BY node.reason_id,node.ordinal LIMIT CAST(?2 AS INTEGER);
