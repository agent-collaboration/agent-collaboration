SELECT CAST(child.row_id AS TEXT) AS row_id,
typeof(child.row_id) AS row_id_class,
CAST(child.entry_id AS TEXT) AS entry_id,
typeof(child.entry_id) AS entry_id_class,
CAST(child.ordinal AS TEXT) AS ordinal,
typeof(child.ordinal) AS ordinal_class,
CAST(child.repository_origin AS TEXT) AS repository_origin,
typeof(child.repository_origin) AS repository_origin_class,
CAST(child.path AS TEXT) AS path,
typeof(child.path) AS path_class,
CAST(child.commit_sha AS TEXT) AS commit_sha,
typeof(child.commit_sha) AS commit_sha_class,
CAST(child.created_at AS TEXT) AS created_at,
typeof(child.created_at) AS created_at_class,
CAST(child.updated_at AS TEXT) AS updated_at,
typeof(child.updated_at) AS updated_at_class
FROM fleet_feed_adr_repository_files AS child JOIN (SELECT entry_id FROM fleet_feed WHERE position>CAST(? AS INTEGER) ORDER BY position LIMIT CAST(? AS INTEGER)) AS parent ON parent.entry_id=child.entry_id ORDER BY child.entry_id,child.ordinal;
