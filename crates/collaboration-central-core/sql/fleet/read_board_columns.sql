    typeof(board_id) AS board_id_class,
    CAST(workspace_id AS TEXT) AS workspace_id,
    typeof(workspace_id) AS workspace_id_class,
    CAST(name AS TEXT) AS name,
    typeof(name) AS name_class,
    CAST(description AS TEXT) AS description,
    typeof(description) AS description_class,
    CAST(board_kind AS TEXT) AS board_kind,
    typeof(board_kind) AS board_kind_class,
    CAST(initiative_goal AS TEXT) AS initiative_goal,
    typeof(initiative_goal) AS initiative_goal_class,
    CAST(initiative_done_when AS TEXT) AS initiative_done_when,
    typeof(initiative_done_when) AS initiative_done_when_class,
    CAST(state AS TEXT) AS state,
    typeof(state) AS state_class,
    CAST(actor_kind AS TEXT) AS actor_kind,
    typeof(actor_kind) AS actor_kind_class,
    CAST(actor_human_id AS TEXT) AS actor_human_id,
    typeof(actor_human_id) AS actor_human_id_class,
