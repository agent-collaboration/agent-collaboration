    typeof(request_id) AS request_id_class,
    CAST(fleet_position AS TEXT) AS fleet_position,
    typeof(fleet_position) AS fleet_position_class,
    CAST(router_time AS TEXT) AS router_time,
    typeof(router_time) AS router_time_class,
    CAST(time_basis AS TEXT) AS time_basis,
    typeof(time_basis) AS time_basis_class,
