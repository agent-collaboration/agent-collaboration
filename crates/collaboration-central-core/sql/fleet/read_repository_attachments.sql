SELECT CAST(attachment_id AS TEXT) AS attachment_id,
    typeof(attachment_id) AS attachment_id_class,
    CAST(workspace_id AS TEXT) AS workspace_id,
    typeof(workspace_id) AS workspace_id_class,
    CAST(reference_kind AS TEXT) AS reference_kind,
    typeof(reference_kind) AS reference_kind_class,
    CAST(normalized_origin AS TEXT) AS normalized_origin,
    typeof(normalized_origin) AS normalized_origin_class,
    CAST(service_id AS TEXT) AS service_id,
    typeof(service_id) AS service_id_class,
    CAST(common_directory AS TEXT) AS common_directory,
    typeof(common_directory) AS common_directory_class,
    CAST(router_time AS TEXT) AS router_time,
    typeof(router_time) AS router_time_class,
    CAST(time_basis AS TEXT) AS time_basis,
    typeof(time_basis) AS time_basis_class,
    CAST(origin_installation AS TEXT) AS origin_installation,
    typeof(origin_installation) AS origin_installation_class,
    CAST(origin_machine AS TEXT) AS origin_machine,
    typeof(origin_machine) AS origin_machine_class,
    CAST(import_digest AS TEXT) AS import_digest,
    typeof(import_digest) AS import_digest_class,
    CAST(created_at AS TEXT) AS created_at,
    typeof(created_at) AS created_at_class,
    CAST(updated_at AS TEXT) AS updated_at,
    typeof(updated_at) AS updated_at_class
FROM fleet_repository_attachments WHERE workspace_id=?;
