SELECT CAST(child.row_id AS TEXT) AS row_id,
typeof(child.row_id) AS row_id_class,
CAST(child.entry_id AS TEXT) AS entry_id,
typeof(child.entry_id) AS entry_id_class,
CAST(child.ordinal AS TEXT) AS ordinal,
typeof(child.ordinal) AS ordinal_class,
CAST(child.reference_kind AS TEXT) AS reference_kind,
typeof(child.reference_kind) AS reference_kind_class,
CAST(child.normalized_origin AS TEXT) AS normalized_origin,
typeof(child.normalized_origin) AS normalized_origin_class,
CAST(child.service_id AS TEXT) AS service_id,
typeof(child.service_id) AS service_id_class,
CAST(child.common_directory AS TEXT) AS common_directory,
typeof(child.common_directory) AS common_directory_class,
CAST(child.created_at AS TEXT) AS created_at,
typeof(child.created_at) AS created_at_class,
CAST(child.updated_at AS TEXT) AS updated_at,
typeof(child.updated_at) AS updated_at_class
FROM fleet_feed_repository_refs AS child JOIN (SELECT entry_id FROM fleet_feed WHERE position>CAST(? AS INTEGER) ORDER BY position LIMIT CAST(? AS INTEGER)) AS parent ON parent.entry_id=child.entry_id ORDER BY child.entry_id,child.ordinal;
